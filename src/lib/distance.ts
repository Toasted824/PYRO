export function haversine(lat1: number, lon1: number, lat2: number, lon2: number) {
  const R = 6371
  const dLat = ((lat2 - lat1) * Math.PI) / 180
  const dLon = ((lon2 - lon1) * Math.PI) / 180
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2)
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
  return R * c
}

// center for distance calc - approximate city center (Kathmandu for demo, but generic)
export const CENTER = { lat: 27.7172, lng: 85.324 }

export function distanceFromCenter(lat: number, lng: number) {
  return haversine(CENTER.lat, CENTER.lng, lat, lng)
}
